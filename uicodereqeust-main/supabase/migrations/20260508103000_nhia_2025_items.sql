-- Official NHIA 2025 item search table for staging nurse approvals.

BEGIN;

CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TABLE IF NOT EXISTS public.nhia_items (
  code TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  category TEXT NOT NULL,
  subcategory TEXT,
  amount NUMERIC(12,2) NOT NULL CHECK (amount >= 0),
  dosage_form TEXT,
  strengths TEXT,
  presentation TEXT,
  description TEXT,
  common_abbreviations TEXT[],
  is_active BOOLEAN DEFAULT true,
  created_at TIMESTAMPTZ DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.abbreviations (
  id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
  shorthand TEXT NOT NULL,
  item_code TEXT REFERENCES public.nhia_items(code) ON DELETE CASCADE,
  confidence TEXT DEFAULT 'high',
  created_at TIMESTAMPTZ DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_nhia_category ON public.nhia_items(category);
CREATE INDEX IF NOT EXISTS idx_nhia_subcategory ON public.nhia_items(subcategory);
CREATE INDEX IF NOT EXISTS idx_nhia_name ON public.nhia_items(name);
CREATE INDEX IF NOT EXISTS idx_nhia_abbrev ON public.nhia_items USING gin(common_abbreviations);
CREATE INDEX IF NOT EXISTS idx_abbrev_shorthand ON public.abbreviations(shorthand);
CREATE UNIQUE INDEX IF NOT EXISTS idx_abbrev_shorthand_item_unique ON public.abbreviations(lower(shorthand), item_code);

ALTER TABLE public.nhia_items ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.abbreviations ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "nhia_items_read_all" ON public.nhia_items;
CREATE POLICY "nhia_items_read_all" ON public.nhia_items FOR SELECT TO authenticated USING (true);

DROP POLICY IF EXISTS "abbreviations_read_all" ON public.abbreviations;
CREATE POLICY "abbreviations_read_all" ON public.abbreviations FOR SELECT TO authenticated USING (true);

